def main():
    today = datetime.now(TIMEZONE).date()

    if today < START_DATE:
        print("لم يحن موعد بداية النشر بعد.")
        return

    day_number = (today - START_DATE).days

    if day_number >= len(QUOTES):
        print("اكتملت قائمة الحكم. أضف حكماً جديدة للمتابعة.")
        return

    quote, category = QUOTES[day_number]

    message = (
        "✨ حِكمة اليوم ✨\n\n"
        f"❝ {quote} ❞\n\n"
        f"📚 التصنيف: {category}\n\n"
        "❤️ إذا أعجبتك الحكمة، شاركها مع من تحب.\n\n"
        "#حكم #اقتباسات #حكمة_اليوم"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"

    response = requests.post(
        url,
        json={"chat_id": CHANNEL_ID, "text": message},
        timeout=20
    )
    response.raise_for_status()

    if not response.json().get("ok"):
        raise RuntimeError("فشل النشر على تيليغرام")

    print(f"تم نشر حكمة اليوم رقم {day_number + 1}")

if __name__ == "__main__":
    main()
